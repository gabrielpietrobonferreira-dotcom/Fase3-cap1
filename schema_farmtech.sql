CREATE TABLE FT_SENSOR_LEITURAS (
    LEITURA_ID       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    DATA_HORA        TIMESTAMP NOT NULL,
    UMIDADE          NUMBER(6,2),
    PH               NUMBER(6,2),
    FOSFORO          NUMBER(1),
    POTASSIO         NUMBER(1),
    NITROGENIO       NUMBER(1),
    BOMBA            NUMBER(1),
    SIMULADO         NUMBER(1) DEFAULT 0 NOT NULL,
    CHUVA_PREVISTA   NUMBER(1),
    UMIDADE_MM       NUMBER(6,2),
    PH_MM            NUMBER(6,2),
    DURACAO_MIN      NUMBER(8,2),
    BOMBA_MIN        NUMBER(8,2),
    AGUA_ESTIMADA_L  NUMBER(12,2),
    ACIONAMENTO      NUMBER(1),
    CONSTRAINT PK_FT_SENSOR_LEITURAS PRIMARY KEY (LEITURA_ID),
    CONSTRAINT UK_FT_SENSOR_DATA UNIQUE (DATA_HORA),
    CONSTRAINT CK_FT_SENSOR_UMIDADE CHECK (UMIDADE IS NULL OR UMIDADE BETWEEN 0 AND 100),
    CONSTRAINT CK_FT_SENSOR_PH CHECK (PH IS NULL OR PH BETWEEN 0 AND 14),
    CONSTRAINT CK_FT_SENSOR_FOSFORO CHECK (FOSFORO IS NULL OR FOSFORO IN (0,1)),
    CONSTRAINT CK_FT_SENSOR_POTASSIO CHECK (POTASSIO IS NULL OR POTASSIO IN (0,1)),
    CONSTRAINT CK_FT_SENSOR_NITROGENIO CHECK (NITROGENIO IS NULL OR NITROGENIO IN (0,1)),
    CONSTRAINT CK_FT_SENSOR_BOMBA CHECK (BOMBA IS NULL OR BOMBA IN (0,1)),
    CONSTRAINT CK_FT_SENSOR_SIMULADO CHECK (SIMULADO IN (0,1)),
    CONSTRAINT CK_FT_SENSOR_CHUVA CHECK (CHUVA_PREVISTA IS NULL OR CHUVA_PREVISTA IN (0,1)),
    CONSTRAINT CK_FT_SENSOR_ACIONAMENTO CHECK (ACIONAMENTO IS NULL OR ACIONAMENTO IN (0,1))
);

CREATE TABLE FT_BOMBA_HISTORICO (
    EVENTO_ID        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    LEITURA_ID       NUMBER NOT NULL,
    DATA_HORA        TIMESTAMP NOT NULL,
    ESTADO_BOMBA     NUMBER(1),
    ACIONAMENTO      NUMBER(1),
    DURACAO_MIN      NUMBER(8,2),
    BOMBA_MIN        NUMBER(8,2),
    AGUA_ESTIMADA_L  NUMBER(12,2),
    CONSTRAINT PK_FT_BOMBA_HIST PRIMARY KEY (EVENTO_ID),
    CONSTRAINT UK_FT_BOMBA_DATA UNIQUE (DATA_HORA),
    CONSTRAINT FK_FT_BOMBA_LEITURA FOREIGN KEY (LEITURA_ID)
        REFERENCES FT_SENSOR_LEITURAS (LEITURA_ID),
    CONSTRAINT CK_FT_BOMBA_ESTADO CHECK (ESTADO_BOMBA IS NULL OR ESTADO_BOMBA IN (0,1)),
    CONSTRAINT CK_FT_BOMBA_ACIONAMENTO CHECK (ACIONAMENTO IS NULL OR ACIONAMENTO IN (0,1))
);

CREATE TABLE FT_MANEJO_CULTURAS (
    MANEJO_ID        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    CHAVE_REGISTRO   VARCHAR2(300) NOT NULL,
    TIPO_REGISTRO    VARCHAR2(100) NOT NULL,
    ARQUIVO_ORIGEM   VARCHAR2(255) NOT NULL,
    DADOS_JSON       CLOB NOT NULL,
    DATA_CARGA       TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_FT_MANEJO PRIMARY KEY (MANEJO_ID),
    CONSTRAINT UK_FT_MANEJO_ORIGEM UNIQUE (ARQUIVO_ORIGEM, CHAVE_REGISTRO)
);

CREATE INDEX IX_FT_MANEJO_TIPO ON FT_MANEJO_CULTURAS(TIPO_REGISTRO);

-- Consultas de gestão. Execute depois de carregar os dados.

-- 1. Volume estimado de água por mês.
SELECT TO_CHAR(DATA_HORA, 'YYYY-MM') AS MES,
       SUM(AGUA_ESTIMADA_L) AS TOTAL_AGUA_LITROS
FROM FT_SENSOR_LEITURAS
GROUP BY TO_CHAR(DATA_HORA, 'YYYY-MM')
ORDER BY MES;

-- 2. Evolução temporal do pH demonstrativo.
SELECT DATA_HORA, PH
FROM FT_SENSOR_LEITURAS
WHERE PH IS NOT NULL
ORDER BY DATA_HORA;

-- 3. Dias com mais horas de bomba ligada.
SELECT TRUNC(DATA_HORA) AS DIA_OPERACAO,
       SUM(BOMBA_MIN) / 60 AS HORAS_BOMBA_LIGADA
FROM FT_SENSOR_LEITURAS
GROUP BY TRUNC(DATA_HORA)
ORDER BY HORAS_BOMBA_LIGADA DESC;

-- 4. Umidade média por estado da bomba.
SELECT BOMBA AS ESTADO_BOMBA,
       ROUND(AVG(UMIDADE), 2) AS UMIDADE_MEDIA,
       COUNT(*) AS TOTAL_LEITURAS
FROM FT_SENSOR_LEITURAS
WHERE UMIDADE IS NOT NULL
GROUP BY BOMBA
ORDER BY BOMBA;

-- 5. Percentual de horas com os botões de nutrientes marcados como disponíveis.
SELECT ROUND(AVG(NITROGENIO) * 100, 2) AS PCT_NITROGENIO,
       ROUND(AVG(FOSFORO) * 100, 2) AS PCT_FOSFORO,
       ROUND(AVG(POTASSIO) * 100, 2) AS PCT_POTASSIO
FROM FT_SENSOR_LEITURAS;
